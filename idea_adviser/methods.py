"""発想法(アイデア発想フレームワーク)の定義。

各発想法を ``Method`` として定義する。``Method.steps`` はその発想法が
アイデアを論理的に洗い出すために辿る手順であり、各 ``Step.prompt`` の
``{topic}`` は実際に検討したいお題(入力内容)に置き換えて使う。

``keywords`` はオーケストレーターの選定ロジック(``selector.py``)が
入力内容とのマッチ度を測るために使う手がかり語であり、"この発想法が
向いている状況"を表す語を集めている。``best_for`` (この発想法が向いて
いる場面の説明文、具体例を含む)も selector.py 側で語句抽出され、
``keywords`` を補うマッチング材料として使われる。
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Step:
    """発想法における1つの検討ステップ。"""

    title: str
    prompt: str  # "{topic}" を含む質問テンプレート
    note: str = ""

    def render(self, topic: str) -> str:
        return self.prompt.format(topic=topic)


@dataclass(frozen=True)
class Method:
    """1つの発想法(フレームワーク)。"""

    id: str
    name_ja: str
    name_en: str
    summary: str
    benefits: tuple[str, ...]
    best_for: tuple[str, ...]  # この発想法が向いている状況の説明(選定理由の材料)
    keywords: tuple[str, ...]  # 選定ロジックが使うマッチング語
    steps: tuple[Step, ...]
    priority: int = 0  # スコアが同点のときのタイブレーク用(小さいほど優先)


